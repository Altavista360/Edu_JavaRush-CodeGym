# Напишите тут ваш код

foo = tuple(input(f"Введите элемент {i+1}: ") for i in range(5))

bar = int(input("Введите индекс: "))

if 0 <= bar < len(foo):
    print(f"Элемент с индексом {bar} это {foo[bar]}")
else:
    print("Индекс за пределами границ кортежа")


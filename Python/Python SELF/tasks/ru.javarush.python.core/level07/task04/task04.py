person_dict = {
    "name": "John",
    "age": 27,
    "city": "Atlanta"
}
name = person_dict['name']
print(f'Name: {name}')
age = person_dict.get('age')
print(f'Age: {age}')
country = person_dict.setdefault('country', 'USA')
print(f'Country: {country}')

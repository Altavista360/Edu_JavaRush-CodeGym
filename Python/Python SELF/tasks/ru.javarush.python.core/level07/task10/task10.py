# Напишите тут ваш код

book = {
    "название": "Harry Potter and the Order of the Phoenix",
    "автор": "J. R. Rowling",
    "год издания": 2004
}

book["год издания"] = 2003
print("После изменения года издания:", book)

book.setdefault("издательство", "Scholastic")
print("После добавления издательства:", book)

book.update({
    "название": "Harry Potter and the Prisoner of Azkaban",
    "автор": "J. R. Rowling",
    "год издания": 2001
})
print("После обновления нескольких элементов:", book)


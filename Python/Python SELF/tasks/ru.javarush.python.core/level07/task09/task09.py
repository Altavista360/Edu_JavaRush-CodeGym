student = {
    "name": "Robert",
    "age": 21
}

student["university"] = "MTI"
print("После добавления 'university':", student)

if "city" not in student:
    student["city"] = "Москва"
print("После возможного добавления 'city':", student)

student.update({"faculty": "Физический", "year": 3})
print("После добавления новых элементов с использованием update():", student)


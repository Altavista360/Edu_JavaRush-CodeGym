import math
number = float(input("Введите число: "))
floor_number = math.floor(number)
ceil_number = math.ceil(number)
round_number = round(number)
print(f"Округление вниз: {floor_number}")
print(f"Округление вверх: {ceil_number}")
print(f"Округление до ближ. целого: {round_number}")


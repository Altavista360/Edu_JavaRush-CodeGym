import random
foo = set(random.randint(1, 20) for _ in range(10))
bar = set(random.randint(10, 30) for _ in range(10))
difference = foo.difference(bar)
symmetric_difference = foo.symmetric_difference(bar)
print("1-ое множество:", foo)
print("2-ое множество:", bar)
print("Разность 1-го множества со 2-ым:", difference)
print("Симметрическая разность:", symmetric_difference)


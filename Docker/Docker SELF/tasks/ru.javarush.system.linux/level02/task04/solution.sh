### JavaRush
## Требования:
# • Необходимо установить маску `0022` с использованием команды `umask`.
# • Требуется создать директорию `task4_dir` и файл `task4.txt` внутри этой директории.
# • Файлу `task4.txt` необходимо назначить права доступа: - Владельцу - чтение и выполнение. - Группе - выполнение. - Остальным пользователям - чтение.
# • Владельцем файла `task4.txt` должен стать пользователь `root`, а группа должна быть изменена на `sudo` (командой `sudo chown`).
# • Необходимо проверить права доступа, владельца и группу файла `task4.txt` с использованием команды `ls -l task4_dir/task4.txt`.


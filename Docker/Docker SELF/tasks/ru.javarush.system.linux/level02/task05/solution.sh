## Условие:
# Создайте нового пользователя с именем `new_user` с помощью команды `adduser`. Пароль можно задать произвольным.
# Проверьте, что пользователь действительно создан, используя команду для просмотра файла `/etc/passwd`. Команда должна найти информацию о созданном пользователе.

### JavaRush
## Требования:
# • Пользователь должен быть создан с использованием команды `adduser`.
# • Имя нового пользователя должно быть `new_user`.
# • Пароль для пользователя должен быть задан при выполнении команды `adduser`.
# • Нужно проверить, что пользователь `new_user` добавлен в систему, используя просмотр файла `/etc/passwd`.
# • Команда для проверки файла `/etc/passwd` должна находить строку, соответствующую пользователю `new_user`.


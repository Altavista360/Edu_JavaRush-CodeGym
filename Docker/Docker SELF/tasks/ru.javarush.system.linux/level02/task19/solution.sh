### JavaRush
# Команда `top` для ручной сортировки по CPU
echo "Откройте команду 'top' и отсортируйте процессы по использованию CPU."
echo "Для сортировки по CPU используйте Shift+P."
echo "После этого определите PID самого ресурсоёмкого процесса."
echo "Введите PID самого ресурсоёмкого процесса:"

# Ввод пользователем PID процесса
read PID

# Получение информации о ресурсоёмком процессе с использованием команды `ps`
ps -p "$PID" -o pid,user,%cpu,%mem,cmd


### JavaRush
# Создание новой группы с именем testgroup
sudo groupadd testgroup

# Добавление текущего пользователя в группу testgroup
sudo usermod -aG testgroup $(whoami)

# Новая группа попадает в сеанс только после повторного входа в систему, поэтому
# `groups` и `id` без аргументов в уже открытом сеансе её ещё не покажут.
# С именем пользователя обе команды читают актуальный список групп из системы.

# Проверка обновленного списка групп для текущего пользователя
groups $(whoami)

# Подтверждение принадлежности к новой группе
id $(whoami)

# Убеждаемся, что testgroup есть в выводе обеих команд
if groups $(whoami) | grep -qw testgroup && id $(whoami) | grep -qw testgroup; then
    echo "Группа testgroup есть в выводе groups и id"
else
    echo "Группы testgroup нет в выводе groups или id"
    exit 1
fi


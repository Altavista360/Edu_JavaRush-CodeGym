### JavaRush
## Условие:
# 1. Создайте файл `project.txt` в домашней директории пользователя `user1`.
# 2. Измените владельца файла на `user1`, а группу — на `developers`.
# 3. Настройте права таким образом, чтобы только владелец и члены группы могли читать и изменять файл, а остальные пользователи не имели к нему доступа.
# 4. Проверьте итоговые права доступа на файл, выполнив команду `ls`.

### JavaRush
## Требования:
# • Файл `project.txt` должен быть создан в домашней директории пользователя `user1`.
# • Необходимо установить владельцем файла `project.txt` пользователя `user1`.
# • Необходимо установить группой файла `project.txt` группу `developers`.
# • Владелец файла должен иметь права на чтение и запись.
# • Члены группы `developers` должны иметь права на чтение и запись файла.
# • Для остальных пользователей доступ к файлу (`project.txt`) должен быть полностью запрещён.
# • Должна быть выполнена команда `chmod` для настройки необходимых прав доступа.
# • Итоговые права доступа к файлу должны быть проверены с помощью команды `ls`.


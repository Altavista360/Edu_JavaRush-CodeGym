### JavaRush
# Запуск фоновых процессов с разным временем ожидания
sleep 10 &  # первый процесс (10 секунд)
PID1=$!     # сохраняем PID первого процесса
echo "Первый процесс запущен с PID=${PID1}"

sleep 20 &  # второй процесс (20 секунд)
PID2=$!     # сохраняем PID второго процесса
echo "Второй процесс запущен с PID=${PID2}"

sleep 30 &  # третий процесс (30 секунд)
PID3=$!     # сохраняем PID третьего процесса
echo "Третий процесс запущен с PID=${PID3}"

# Делаем паузу для наглядности
sleep 1
echo "Все три процесса запускаются в фоновом режиме."


# Завершение одного процесса (первого) с использованием команды kill
echo "Завершаем первый процесс командой kill с PID=${PID1}"
if kill $PID1; then
    wait $PID1 2>/dev/null
    echo "Успешно. 1-ый процесс с PID=${PID1} завершён."
else
    echo "Ошибка. Не удалось завершить процесс с PID=${PID1}."
fi

# Завершение оставшихся процессов (второй и третий) с использованием команды killall
echo "Завершаем оставшиеся процессы (PID=${PID2}, PID=${PID3}) командой killall"
if killall sleep; then
    wait $PID2 $PID3 2>/dev/null
    echo "Успешно. Оставшиеся процессы завершены."
else
    echo "Ошибка. Команда killall не смогла завершить."
fi

# Проверка текущих процессов с помощью команды ps
echo "Проверяем активные процессы sleep с помощью команды ps:"
if ps aux | grep "[s]leep"; then
    echo "Ошибка. Процессы sleep всё ещё активны."
else
    echo "ps не нашла активных процессов sleep."
fi


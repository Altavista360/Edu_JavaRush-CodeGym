### JavaRush
## Требования:
# • Скрипт должен использовать команду `id` без параметров для вывода информации о текущем пользователе.
# • Скрипт должен отобразить идентификатор пользователя (UID).
# • Скрипт должен отобразить идентификатор основной группы пользователя (GID).
# • Скрипт должен отобразить список всех групп, к которым принадлежит текущий пользователь.
# • Команда должна выполняться для пользователя, вызывающего скрипт, без необходимости указывать дополнительные параметры.
# • Скрипт должен предоставить информацию в удобном и читаемом формате, аналогичном стандартному выводу команды `id`.


### JavaRush
## Условие:
# 1. Проверьте текущую маску прав доступа с помощью команды `umask`.
# 2. Установите новую маску `027`.
# 3. Создайте файл с именем `task3.txt`.
# 4. Проверьте права доступа созданного файла, используя команду `ls -l task3.txt`.

### JavaRush
## Требования:
# • Скрипт должен использовать команду `umask` для определения текущей маски прав доступа.
# • Необходимо установить новую маску прав доступа равную `027` с использованием команды `umask`.
# • Должен быть создан файл с именем `task3.txt` после изменения маски прав доступа.
# • Скрипт должен проверить и отобразить права доступа созданного файла с помощью команды `ls -l task3.txt`.
# • Права доступа к файлу `task3.txt` должны соответствовать установленной маске `027` (файл должен быть создан с ожидаемыми правами).


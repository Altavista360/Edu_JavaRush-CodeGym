### JavaRush
## Условие:
# Создайте двух пользователей в системе с именами `user1` и `user2`. Проверьте, создались ли их домашние директории в каталоге `/home`, выполнив команду `ls`.

### JavaRush
## Требования:
# • Необходимо использовать команду `adduser` для создания пользователей `user1` и `user2`.
# • У новых пользователей должны автоматически создаваться домашние директории в каталоге `/home`.
# • После создания пользователей выполните команду `ls /home` для проверки наличия соответствующих директорий `user1` и `user2`.
# • Имя первого пользователя должно быть `user1`, а второго - `user2`.
# • Созданные пользователи могут быть использованы для аутентификации в системе.
# • Выведите сведения о домашних каталогах командами `ls -ld /home/user1` и `ls -ld /home/user2` — в их выводе владельцем каждого каталога должен быть соответствующий пользователь.


### JavaRush
# Создаем первого пользователя user1
# Пароль задаётся в интерактивном режиме в процессе выполнения команды,
# поэтому учётная запись пригодна для входа в систему
sudo adduser user1

# Создаем второго пользователя user2
sudo adduser user2

# Проверяем, существуют ли домашние директории для пользователей
ls /home

# Проверяем права собственности на домашние директории
ls -ld /home/user1
ls -ld /home/user2


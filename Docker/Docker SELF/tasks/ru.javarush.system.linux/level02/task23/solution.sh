### JavaRush
## Условие:
# Запустите следующие процессы:
# # sleep 500 &
# # sleep 600 &
# # sleep 700 &
# Используя команду `pkill` и шаблон, завершите все процессы, содержащие слово `sleep` в имени. Проверьте, что процессы завершены с помощью команды `ps`.

### JavaRush
## Требования:
# • Необходимо запустить три процесса с использованием команды `sleep` с разным временем (500, 600, 700) в фоне.
# • Для завершения процессов нужно использовать команду `pkill` с указанием шаблона `sleep`.
# • Команда `pkill` должна завершить все процессы, содержащие слово `sleep` в имени.
# • После выполнения команды `pkill` необходимо использовать команду `ps` для проверки, что процессы с именем `sleep` больше не активны.


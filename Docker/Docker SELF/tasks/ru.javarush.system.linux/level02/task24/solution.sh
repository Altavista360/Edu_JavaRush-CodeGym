### JavaRush
## Условие:
# Создайте нового пользователя с помощью команды `adduser` (при наличии прав суперпользователя). Затем выполните вход от имени этого пользователя (или используйте `su`) и запустите несколько процессов:
# # sleep 800 &
# # sleep 900 &
# Вернитесь к суперпользователю или основному пользователю и завершите все процессы, принадлежащие новому пользователю, с помощью `pkill -u username` (замените `username` на имя нового пользователя). Процессы завершены должны быть завершены.

### JavaRush
## Требования:
# • Необходимо создать нового пользователя с помощью команды `adduser`, если у пользователя имеются права суперпользователя.
# • Необходимо войти в систему под созданным пользователем, используя его учетные данные, или переключиться к нему с помощью команды `su`.
# • От имени нового пользователя требуется запустить два фоновых процесса с использованием команды `sleep 800 &` и `sleep 900 &`.
# • Использовать команду `pkill -u username` (где `username` — имя нового пользователя) для завершения всех процессов, запущенных этим пользователем.


### JavaRush
## Условие:
# С помощью команды `ps` выведите древовидную структуру всех процессов, чтобы увидеть взаимосвязи между ними.

### JavaRush
## Требования:
# • Необходимо использовать команду `ps` для выполнения задания.
# • Результат выполнения команды должен содержать древовидную структуру, показывающую взаимосвязи между процессами.
# • Команда должна выводить полный список всех процессов, а не только процессов текущего пользователя или текущего терминала.
# • Для отображения древовидной структуры нужно использовать соответствующие параметры команды `ps` (например, `--forest` или подобные в зависимости от системы).
# • Вывод должен быть читаемым и показывать родительско-дочерние отношения между процессами.
# • Задача предполагает выполнение команды непосредственно в командной строке.


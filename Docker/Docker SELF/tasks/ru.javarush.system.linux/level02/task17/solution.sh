## Условие:
# Используйте команду `ps`, чтобы отобразить список всех запущенных процессов, включая те, которые не привязаны к вашему терминалу. Вывод должен быть в удобочитаемом формате с информацией о пользователе, PID, использовании CPU и памяти.

### JavaRush
## Требования:
# • Задача требует воспользоваться командой `ps` для отображения списка процессов.
# • Команда должна выводить не только процессы, связанные с текущим терминалом, но и все остальные процессы.
# • Вывод команды должен быть представлен в удобочитаемом формате.
# • На выходе должна быть отображена информация о пользователе, которому принадлежит процесс.
# • Вывод должен содержать идентификатор процесса (PID).
# • В списке процессов должна быть отображена информация об использовании процессором (CPU).
# • Список процессов должен включать данные об использовании памяти.

### JavaRush
## Черновик:
# # Просмотр всех процессов, включая те, которые не привязаны к текущему терминалу,
# # с информацией о пользователе, PID, использовании CPU и памяти.

### JavaRush
# Просмотр всех процессов, включая те, которые не привязаны к текущему терминалу,
# с информацией о пользователе, PID, использовании CPU и памяти.
ps aux --sort=-%cpu | awk 'NR==1; NR > 1 {print $0}' | column -t


### JavaRush
## Условие:
# Настройка паролей пользователей
# 1. Для пользователя `developer` установите новый пароль.
# 2. Настройте пользователя так, чтобы он был вынужден сменить пароль при следующем входе.
# 3. Проверьте настройки пользователя, убедившись, что параметр смены пароля активирован.
# Используйте подходящие команды для завершения задачи.

### JavaRush
## Требования:
# • Пользователю `developer` должен задаваться новый пароль. В скрипте это делается неинтерактивно — например, `echo developer:password | chpasswd`: команда `passwd developer` запросила бы ввод с клавиатуры и в скрипте не отработала бы.
# • Используйте команду `passwd -e developer` для настройки пользователя таким образом, чтобы он был вынужден сменить пароль при следующем входе.
# • Параметр смены пароля должен быть активирован. Например, с помощью команды `chage -l developer`.


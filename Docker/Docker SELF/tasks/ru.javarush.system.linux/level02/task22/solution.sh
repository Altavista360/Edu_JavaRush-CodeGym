### JavaRush
## Условие:
# Запустите несколько процессов с командой:
# # sleep 100 &
# # sleep 150 &
# # sleep 200 &
# Используя команду `killall`, завершите все процессы с именем `sleep`. Не должно остаться ни одного процесса `sleep`.

### JavaRush
## Требования:
# • Задача требует применения команды `killall` для завершения процессов.
# • Команда `killall` должна быть выполнена для завершения всех процессов, связанных с именем `sleep`.
# • После выполнения команды не должно остаться ни одного активного процесса с именем `sleep`.
# • Перед использованием команды `killall` нужно запустить указанные процессы с помощью команд `sleep 100 &`, `sleep 150 &`, `sleep 200 &`.
# • Каждый процесс `sleep` должен быть запущен в фоновом режиме с использованием символа `&`.
# • Завершение процессов должно быть выполнено корректно, без ошибок или предупреждений.
# • Рекомендуется использовать команду `ps` или аналог для проверки списка процессов до и после выполнения `killall`.


## Условие:
# Запустите три фоновых процесса с командами:
# # sleep 200 &
# # sleep 300 &
# # sleep 400 &
# Используя команду `ps`, найдите PID одного из запущенных процессов и завершите его с помощью команды `kill`. Убедитесь, что процесс завершён, выполнив команду `ps` ещё раз.

### JavaRush
## Требования:
# • Скрипт должен запустить три фоновых процесса с командами `sleep 200 &`, `sleep 300 &`, и `sleep 400 &`.
# • Скрипт должен отобразить список текущих процессов, чтобы найти PID одного из запущенных процессов.
# • Скрипт должен завершить один из процессов, используя его PID и команду `kill`.
# • Скрипт должен выполнить команду `ps` после завершения процесса, чтобы убедиться, что процесс больше не отображается в списке.
# • При завершении процесса с помощью команды `kill` нужно использовать PID из списка, предоставленного командой `ps`.
# • Каждый процесс `sleep` должен быть запущен в фоновом режиме, используя символ `&`.
# • Процесс завершения и проверки должен происходить без ошибок и с учётом корректной последовательности действий.
# • Команда `ps` должна быть использована как минимум дважды — до и после завершения процесса.


### JavaRush
# Запуск трёх фоновых процессов
sleep 200 &  # Процесс 1
sleep 300 &  # Процесс 2
sleep 400 &  # Процесс 3

# Пауза, чтобы процессы успели запуститься
sleep 1

# Вывод списка текущих процессов для поиска PID.
# Столбец args показывает команду вместе с аргументами: в обычном выводе ps
# у всех трёх процессов стоит одно имя sleep, и нужный по нему не найти
echo "Список текущих процессов:"
ps_list=$(ps -o pid,ppid,args)
echo "$ps_list"

# Получение PID процесса `sleep 300` из показанного списка.
# Поля сравниваются точно: родитель — этот скрипт ($$), команда — sleep, аргумент — 300,
# поэтому в выборку не попадёт ни сам фильтр, ни чужой sleep, и PID будет ровно один
pid_to_kill=$(echo "$ps_list" | awk -v parent=$$ '$2 == parent && $3 == "sleep" && $4 == "300" { print $1; exit }')
if [ -z "$pid_to_kill" ]; then
    echo "Процесс sleep 300 не найден в списке ps" >&2
    exit 1
fi

# Завершение процесса с указанным PID
echo "Завершение процесса с PID: $pid_to_kill"
kill "$pid_to_kill"
# wait дожидается, пока процесс завершится, чтобы повторный ps его уже не застал
wait "$pid_to_kill" 2>/dev/null

# Проверка завершения процесса
echo "Список процессов после завершения одного из них:"
ps -o pid,ppid,args
if ps -p "$pid_to_kill" > /dev/null; then
    echo "Процесс с PID $pid_to_kill всё ещё работает" >&2
    exit 1
fi
echo "Процесс с PID $pid_to_kill завершён"


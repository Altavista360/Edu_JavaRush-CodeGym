### JavaRush
# Создание текстового файла с именем `task2.txt`
echo "Lorem ipsum dolor sit amet, consectetur adipiscing elit" > task2.txt

# Смена владельца файла на пользователя `root` и группы на `root` с использованием команды `sudo`
sudo chown root:root task2.txt

# Проверка изменений владельца и группы с помощью команды `ls -l`
ls -l task2.txt


### JavaRush
## Условие:
# 1. С помощью команды `id` определите UID, GID и группы для текущего пользователя.
# 2. С помощью команды `groups` выведите список групп, к которым принадлежит текущий пользователь.

### JavaRush
## Требования:
# • Скрипт должен использовать команду `id` для определения UID, GID и групп текущего пользователя.
# • Команда `id` должна быть использована для отображения информации о текущем пользователе, включая уникальный идентификатор пользователя (UID), уникальный идентификатор группы (GID) и список групп.
# • Скрипт должен использовать команду `groups` для получения списка групп, к которым принадлежит текущий пользователь.
# • Список групп, к которым принадлежит текущий пользователь, должен быть выведен на экран.
# • Обе команды (`id` и `groups`) должны работать в контексте текущего пользователя, запускающего программу.


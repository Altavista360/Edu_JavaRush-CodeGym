/*
 * // JavaRush
 * Условие:
 * Представьте, что вы управляете роботом-уборщиком, который должен выполнить 10 задач, обрабатывая по 2 задачи в минуту. Вам нужно точно знать, сколько минут ему понадобится, но самое важное – по окончании работы он всегда должен сообщить о завершении уборки, независимо от любых непредвиденных обстоятельств.
 * В блоке try разделите 10 на 2 и выведите полученный результат (время выполнения уборки). После этого, независимо от того, что произошло внутри try (даже если бы там была ошибка, хотя здесь её не будет), в блоке finally выведите сообщение: "Робот завершил свою работу. Выполнение завершено." Это гарантирует, что сообщение о завершении будет выведено всегда.
 */

/*
 * // JavaRush
 * Требования:
 * • В программе должен быть использован блок try для выполнения основной логики вычисления времени уборки.
 * • Внутри блока try необходимо разделить 10 на 2 и вывести результат (время выполнения уборки) на экран.
 * • В программе обязательно должен присутствовать блок finally, который выполнится после блока try независимо от возникновения исключений.
 * • Внутри блока finally должно выводиться сообщение: "Робот завершил свою работу. Выполнение завершено."
 */

/*
 * // JavaRush
 * Черновик:
 * package ru.javarush.java.core.level11.task09;
 *
 * public class Solution {
 *     public static void main(String[] args) {
 *
 *         // Выполняем деление 10 на 2 и выводим результат
 *
 *
 *         // Сообщение о завершении работы робота, которое будет выведено всегда
 *
 *
 *     }
 * }
 */

// JavaRush
package ru.javarush.java.core.level11.task09;

public class Solution {
    public static void main(String[] args) {
        try {
            // Выполняем деление 10 на 2 и выводим результат
            int foo = 10;
            int bar = 2;
            int baz = foo / bar;
            System.out.println("Время выполнения уборки: " + baz + " минут.");
        } finally {
            // Сообщение о завершении работы робота, которое будет выведено всегда
            System.out.println("Робот завершил свою работу. Выполнение завершено.");
        }
    }
}


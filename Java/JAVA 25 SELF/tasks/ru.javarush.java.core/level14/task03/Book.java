/*
 * // JavaRush
 * Требования:
 * • Необходимо объявить новый публичный класс с именем Book.
 * • Класс Book должен содержать два поля: строковое поле title и целочисленное поле pages.
 * • В классе Book должен быть метод printInfo(), который выводит на экран информацию о книге в формате: "Название: [название книги], страниц: [количество страниц]".
 * • В методе main необходимо создать объект класса Book с названием "Java для начинающих" и количеством страниц 350.
 * • В методе main после создания объекта Book нужно вызвать его метод printInfo(), чтобы вывести информацию о книге на экран.
 */

// JavaRush
package ru.javarush.java.core.level14.task03;

public class Book {
    String title;
    int pages;

    void printInfo() {
        System.out.println("Название: " + title + ", страниц: " + pages);
    }
}


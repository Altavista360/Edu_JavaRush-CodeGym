package ru.javarush.java.core.level05.task05;

import java.util.Scanner;

public class Solution {
    public static void main(String[] args) {
        // Создаем сканер для чтения числа с консоли
        Scanner inputData = new Scanner(System.in);
        System.out.println("Введите высоту обелиска: ");
        int pyramidHeight = inputData.nextInt();

        // Строим обелиск строка за строкой
        for (int row = 1/* инициализация */; row <= pyramidHeight/* условие */; row++/* изменение */) {
            // Количество пробелов слева: уменьшается от (N - 1) до 0
            int foo = pyramidHeight - row;

            // Количество звездочек: растет по формуле (2 * row - 1)
            int bar = 2 * row - 1;

            // Печатаем пробелы для выравнивания
            for (int i = 0 /* инициализация */; i < foo /* условие */; i++ /* изменение */) {
                System.out.print(" ");
            }
            // Печатаем звездочки
            for (int i = 0 /* инициализация */; i < bar /* условие */; i++ /* изменение */) {
                System.out.print("*");
            }
            // Переход на новую строку после каждой строки обелиска
            System.out.println("");
        }
    }
}


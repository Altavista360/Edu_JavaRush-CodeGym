/*
 * // JavaRush
 * Требования:
 * • Программа должна использовать два вложенных цикла для генерации таблицы умножения от 1 до 10.
 * • В каждой строке должны выводиться произведения текущего числа на числа от 1 до 10.
 * • Результаты умножения должны быть выровнены по ширине, чтобы столбцы совпадали по вертикали.
 * • Таблица должна включать все произведения от 1×1 до 10×10, то есть в правом нижнем углу должно быть число 100.
 * • Программа должна выводить таблицу умножения на экран, а не записывать её в файл или другую структуру данных.
 */


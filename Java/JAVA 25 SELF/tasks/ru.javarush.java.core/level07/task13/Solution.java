/*
 * // JavaRush
 * Условие:
 * Вы разрабатываете новую игру и хотите отслеживать достижения игроков, но количество достижений сильно варьируется в зависимости от уровня. Например, на первом уровне может быть 2 достижения, на втором — 4, а на специальном бонусном уровне — только 1. Ваша задача — создать гибкую структуру данных для хранения этих достижений (вы можете выбрать любые числа в качестве идентификаторов достижений). Как только эта структура будет готова, отобразите все достижения, чтобы было видно, какие из них относятся к какому уровню.
 * Создайте зубчатый массив int[][] playerAchievements, состоящий из 3 строк. Первая строка должна содержать 2 элемента, вторая — 4 элемента, а третья — 1 элемент. Заполните все элементы массива числами по вашему выбору (например, 101, 102 и т.д.). Затем выведите каждую строку массива на отдельной строке, разделяя элементы пробелом, чтобы показать достижения по уровням.
 */

/*
 * // JavaRush
 * Требования:
 * • Необходимо создать двумерный массив типа int[][], в котором каждая строка (подмассив) может иметь разную длину.
 * • В массиве playerAchievements должно быть ровно 3 строки: первая строка содержит 2 элемента, вторая — 4 элемента, третья — 1 элемент.
 * • Каждый элемент массива должен быть заполнен целым числом на ваш выбор (например, 101, 102 и т.д.).
 * • Массив playerAchievements должен быть объявлен и заполнен так, чтобы каждая строка имела строго указанное количество элементов, а все элементы были инициализированы.
 * • Необходимо вывести содержимое каждой строки массива playerAchievements на отдельной строке, разделяя элементы внутри строки пробелом.
 * • Вывод должен соответствовать порядку уровней: сначала достижения первого уровня (первая строка), затем второго (вторая строка), затем третьего (третья строка).
 */

/*
 * // JavaRush
 * Черновик:
 * package ru.javarush.java.core.level07.task13;
 *
 * public class Solution {
 *     public static void main(String[] args) {
 *         // Создаем зубчатый массив (каждая "строка" может иметь свою длину)
 *
 *                 // 1-й уровень: 2 достижения
 *                 // 2-й уровень: 4 достижения
 *                 // 3-й (бонусный) уровень: 1 достижение
 *
 *         // Выводим каждую строку массива на отдельной строке
 *
 *         // Печатаем элементы строки, разделяя пробелом
 *
 *         // перед первым элементом пробел не ставим
 *
 *
 *         // перенос строки после каждой "строки" массива
 *
 *
 *     }
 * }
 */

// JavaRush
package ru.javarush.java.core.level07.task13;

public class Solution {
    public static void main(String[] args) {
        // Создаем зубчатый массив (каждая "строка" может иметь свою длину)
        int[][] playerAchievements = new int[3][];
        playerAchievements[0] = new int[]{101, 102}; // 1-й уровень: 2 достижения
        playerAchievements[1] = new int[]{201, 202, 203, 204}; // 2-й уровень: 4 достижения
        playerAchievements[2] = new int[]{301}; // 3-й (бонусный) уровень: 1 достижение

        // Выводим каждую строку массива на отдельной строке
        for (int i = 0; i < playerAchievements.length; i++) {
        // Печатаем элементы строки, разделяя пробелом
            for (int j = 0; j < playerAchievements[i].length; j++) {
        // перед первым элементом пробел не ставим
                if (j > 0) System.out.print(" ");
                System.out.print(playerAchievements[i][j]);
            }
        // перенос строки после каждой "строки" массива
        System.out.println();
        }
    }
}


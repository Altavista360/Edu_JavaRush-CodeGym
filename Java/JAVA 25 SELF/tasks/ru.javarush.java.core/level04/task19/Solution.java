// JavaRush
package ru.javarush.java.core.level04.task19;

public class Solution {
    public static void main(String[] args) {
        int size = 8; // Размер игрового поля (8 строк и 8 столбцов)

        // Внешний цикл по строкам
        for (int i = 0/* инициализация */; i < size/* условие */; i++/* изменение */) {
            // Внутренний цикл по столбцам
            for (int j = 0/* инициализация */; j < size/* условие */; j++/* изменение */) {
                // Клетка белая, если сумма индексов четная; иначе — черная
                System.out.print((i + j) % 2 == 0 ? "_" : "#");
            }
            System.out.println();// Переход на новую строку после каждой строки поля

        }
    }
}

